def clean_list(raw_str):
    res = []
    for line in raw_str.strip().split('\n'):
        # split by commas in case there are multiple on one line
        for item in line.split(','):
            cleaned = item.strip().lower()
            if cleaned:
                res.append(cleaned)
    return res

