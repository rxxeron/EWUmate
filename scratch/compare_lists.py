print(f"Total raw in List 2: {len(list2)}, Unique in List 2: {len(set2)}")

# Interpreted unique variants:
# 1. Unique to List 1 (in List 1 but NOT in List 2)
unique_to_1 = sorted(list(set1 - set2))

# 2. Unique to List 2 (in List 2 but NOT in List 1)
unique_to_2 = sorted(list(set2 - set1))

# 3. Combined symmetric difference (either list but not both)
sym_diff = sorted(list(set1 ^ set2))

# 4. Entire Union deduplicated
union_dedup = sorted(list(set1 | set2))

